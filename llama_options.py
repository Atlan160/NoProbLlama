"""Alle Startoptionen von llama-server mit Bewertung und Erklärung.

speed, quality und memory bewerten, wie stark eine Einstellung wirken kann:
0 = keine, 1 = gering, 2 = mittel, 3 = groß. Es sind Richtwerte, keine Messungen für jedes Modell.
"""

from dataclasses import dataclass, replace

from llama_lang import tr

INT = r"-?\d+"
