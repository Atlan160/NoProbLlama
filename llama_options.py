QUANT_TYPES = ("", "f32", "f16", "bf16", "q8_0", "q4_0", "q4_1", "iq4_nl", "q5_0", "q5_1")
ON_OFF_AUTO = ("", "on", "off", "auto")
ONLY_MULTI_GPU = "Wirkt nur mit mehreren GPUs."


@dataclass(frozen=True)
class Opt:
    key: str
    flag: str
    label: str
    hint: str
    what: str
    kind: str = "entry"  # entry, combo, choice, toggle, flag, file
    values: tuple = ()
    pattern: str = ""
    off_flag: str = ""
    default: str = ""
    speed: int = 0
    quality: int = 0
    memory: int = 0
    speed_note: str = ""
    quality_note: str = ""
    memory_note: str = ""
    tip: str = ""


TEXT_FIELDS = ("label", "hint", "what", "default", "speed_note", "quality_note", "memory_note", "tip")


def _by_impact(opts):
    """Sortiert so, dass die wirkungsvollsten Einstellungen oben stehen, und übersetzt die Texte."""
    ordered = sorted(opts, key=lambda o: (-max(o.speed, o.quality), -o.memory))
    return [replace(o, **{name: tr(getattr(o, name)) for name in TEXT_FIELDS}) for o in ordered]


